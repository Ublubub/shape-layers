export function download(name, data, type = 'application/octet-stream') {
  const blob = data instanceof Blob ? data : new Blob([data], { type });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 2000);
}

// ---------- .mcfunction (datapack / command blocks) ----------
// Runs of identical blocks along X are merged into one /fill.
export function toMcfunction(v) {
  const { W, H, D, kind, mat, meta } = v;
  const out = [
    `# Generated by Shape Layers - ${W}x${H}x${D}`,
    '# Run while standing at the corner you want the build to start from.',
    '# Structure occupies ~0..~' + (W - 1) + ' (x), ~0..~' + (H - 1) + ' (y), ~0..~' + (D - 1) + ' (z).',
  ];
  for (let y = 0; y < H; y++) {
    for (let z = 0; z < D; z++) {
      let x = 0;
      while (x < W) {
        const i = x + z * W + y * W * D;
        if (!kind[i]) { x++; continue; }
        const st = blockState(mat[i], kind[i], meta[i]);
        let x2 = x;
        while (x2 + 1 < W) {
          const j = i + (x2 + 1 - x);
          if (kind[j] !== kind[i] || mat[j] !== mat[i] || meta[j] !== meta[i]) break;
          x2++;
        }
        out.push(x2 === x
          ? `setblock ~${x} ~${y} ~${z} ${st}`
          : `fill ~${x} ~${y} ~${z} ~${x2} ~${y} ~${z} ${st}`);
        x = x2 + 1;
      }
    }
  }
  return out.join('\n') + '\n';
}

// ---------- Sponge Schematic v2 (.schem) for WorldEdit / Litematica ----------
function nbtWriter() {
  let buf = new Uint8Array(4096), view = new DataView(buf.buffer), len = 0;
  const enc = new TextEncoder();
  const ensure = (n) => {
    if (len + n <= buf.length) return;
    const nb = new Uint8Array(Math.max(buf.length * 2, len + n));
    nb.set(buf); buf = nb; view = new DataView(buf.buffer);
  };
  const w = {
    u8(v) { ensure(1); view.setUint8(len, v); len += 1; },
    u16(v) { ensure(2); view.setUint16(len, v); len += 2; },
    i32(v) { ensure(4); view.setInt32(len, v); len += 4; },
    bytes(b) { ensure(b.length); buf.set(b, len); len += b.length; },
    str(s) { const b = enc.encode(s); w.u16(b.length); w.bytes(b); },
    tag(type, name) { w.u8(type); w.str(name); },
    end() { w.u8(0); },
    result() { return buf.slice(0, len); },
  };
  return w;
}

// DataVersion 3953 = Minecraft 1.21 (needed for tuff bricks). WorldEdit upgrades older/newer as needed.
export async function toSchem(v, dataVersion = 3953) {
  const { W, H, D, kind, mat, meta } = v;
  const palette = new Map([['minecraft:air', 0]]);
  const data = [];
  const total = W * H * D;
  for (let i = 0; i < total; i++) {
    let id = 0;
    if (kind[i]) {
      const st = blockState(mat[i], kind[i], meta[i]);
      id = palette.get(st);
      if (id === undefined) { id = palette.size; palette.set(st, id); }
    }
    // varint
    let n = id;
    while (n & ~0x7f) { data.push((n & 0x7f) | 0x80); n >>>= 7; }
    data.push(n);
  }
  const w = nbtWriter();
  w.tag(10, 'Schematic');
  w.tag(3, 'Version'); w.i32(2);
  w.tag(3, 'DataVersion'); w.i32(dataVersion);
  w.tag(2, 'Width'); w.u16(W);
  w.tag(2, 'Height'); w.u16(H);
  w.tag(2, 'Length'); w.u16(D);
  w.tag(3, 'PaletteMax'); w.i32(palette.size);
  w.tag(10, 'Palette');
  for (const [st, id] of palette) { w.tag(3, st); w.i32(id); }
  w.end();
  w.tag(7, 'BlockData'); w.i32(data.length); w.bytes(Uint8Array.from(data));
  w.tag(11, 'Offset'); w.i32(3); w.i32(0); w.i32(0); w.i32(0);
  w.end();
  const raw = w.result();
  const stream = new Blob([raw]).stream().pipeThrough(new CompressionStream('gzip'));
  return new Blob([await new Response(stream).arrayBuffer()], { type: 'application/octet-stream' });
}

// ---------- Material list ----------
export function materialList(summary) {
  const lines = ['Block,Count,Stacks (64),Shulker boxes (1728)'];
  const fmt = (name, n) => lines.push(`${name},${n},${(n / 64).toFixed(1)},${(n / 1728).toFixed(2)}`);
  summary.perMat.forEach((m, i) => {
    if (m.full) fmt(BLOCKS[i].name, m.full);
    if (m.slab) fmt(BLOCKS[i].name + ' Slab', m.slab);
    if (m.stair) fmt(BLOCKS[i].name + ' Stairs', m.stair);
  });
  return lines.join('\n') + '\n';
}

export function stacks(n) {
  const s = Math.floor(n / 64), r = n % 64;
  if (!s) return `${r}`;
  return r ? `${s}×64 + ${r}` : `${s}×64`;
}

